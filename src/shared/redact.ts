/**
 * Псевдонимизация ника для персистящегося журнала (ревью 26.08.2026).
 *
 * Решение владельца 02.08.2026: «ники игроков в файл лога не пишем». Но
 * строка «loadPlayerStats failed» без указания, У КОГО, неразбираема —
 * компромисс: длина + короткий хэш. Строки одной сессии про одного игрока
 * коррелируются. ЧЕСТНАЯ ГРАНИЦА (ревью 26.08.2026): это слабая
 * псевдонимизация, не анонимизация — знающий состав стола подберёт ник
 * перебором десяти кандидатов. Защищает от случайного взгляда в файл,
 * не от целенаправленного восстановления; большего лог поддержки и не
 * обещает (сам файл отправляет владелец ника).
 */
export function redactNick(name: string): string {
  let h = 0;
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) | 0;
  return `ник#${(h >>> 0).toString(36).slice(0, 4)}·${[...name].length}с`;
}
