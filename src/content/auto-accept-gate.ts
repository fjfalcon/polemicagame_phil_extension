/**
 * Общий стоп-кран автопринятия игры.
 *
 * Нужен разведке очереди (features/queue-peek.ts): пока мы на секунду
 * заходим в очередь за списком игроков, автопринятие обязано молчать —
 * иначе при совпадении (очередь добилась до десяти ровно в этот момент)
 * расширение само подтвердит игру, которую игрок не собирался играть.
 *
 * Отдельный модуль, а не флаг внутри auto-start: гасить надо ОБА пути
 * автопринятия — и клики content-скрипта (auto-start), и фоновый инжект,
 * который запускает search-фича.
 *
 * ДВА ПРЕДОХРАНИТЕЛЯ, чтобы автопринятие не осталось выключенным навсегда:
 *  • сторожевой таймер — снимаем сами, если разведка зависла или её код упал
 *    между «включил» и finally;
 *  • releaseForUserAction() — явное действие игрока (нажал «Играть») всегда
 *    важнее нашей разведки и немедленно возвращает автопринятие в строй.
 */
import { log } from "@core/log";

/**
 * Сторож должен переживать всю сетевую часть разведки (жёсткий предел 8с) с
 * запасом. 15с не хватало: стоп-кран взводился ДО window.confirm, который
 * блокирует поток на сколько угодно, и таймер срабатывал ровно перед входом
 * в очередь — защита исчезала именно в опасном сценарии. Теперь стоп-кран
 * взводится вплотную к сетевой части (см. queue-peek.ts), а сторож — просто
 * страховка от незакрытого finally.
 */
const MAX_SUPPRESSION_MS = 30_000;

let suppressed = false;
let watchdog: ReturnType<typeof setTimeout> | null = null;
/** Разведка регистрирует сюда свою отмену: действие игрока обязано её прервать. */
let abortPeek: (() => void) | null = null;

/**
 * Разведка регистрирует ОБЁРТКУ, которая помечает заход отменённым, а не
 * сырой выход из очереди: иначе отмена через этот путь не запрещала бы
 * повторную попытку (сейчас спасает только собственный click-listener
 * разведки — полагаться на такое совпадение нельзя).
 */
export function registerPeekAbort(fn: (() => void) | null): void {
  abortPeek = fn;
}

function clearWatchdog(): void {
  if (watchdog) {
    clearTimeout(watchdog);
    watchdog = null;
  }
}

export function setAutoAcceptSuppressed(value: boolean): void {
  suppressed = value;
  clearWatchdog();
  if (value) {
    watchdog = setTimeout(() => {
      if (!suppressed) return;
      suppressed = false;
      watchdog = null;
      log.warn("auto-accept-gate", "стоп-кран снят сторожевым таймером — разведка не завершилась");
    }, MAX_SUPPRESSION_MS);
  }
}

export function isAutoAcceptSuppressed(): boolean {
  return suppressed;
}

/**
 * Игрок сам нажал «Играть». Его намерение перекрывает любую нашу разведку:
 * возвращаем автопринятие немедленно, чтобы оно отработало эту игру как
 * обычно (если, конечно, включено в настройках — это решает FeatureManager).
 */
export function releaseForUserAction(): void {
  // ПРЕРВАТЬ разведку, а не просто снять стоп-кран: очередь на сервере
  // привязана к ПОЛЬЗОВАТЕЛЮ, а не к сокету, поэтому наш запоздалый
  // `stop_game_search` снял бы игрока с его собственного поиска.
  if (abortPeek) {
    const abort = abortPeek;
    abortPeek = null;
    try {
      abort();
    } catch {
      /* отмена не должна ломать клик игрока */
    }
  }
  if (!suppressed) return;
  suppressed = false;
  clearWatchdog();
  log.info("auto-accept-gate", "игрок начал поиск сам — разведка прервана, автопринятие возвращено");
}
