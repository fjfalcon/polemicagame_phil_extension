/**
 * Порт модальных окон заметок.
 *
 * Диалоги («Заметка об игроке» и «Цвета ников») — самые большие куски
 * player-notes: почти тысяча строк разметки и обработчиков. Выносить их
 * имело смысл только после того, как появился владелец данных
 * (./notes-model): до него диалогу пришлось бы отдавать два десятка методов
 * менеджера, а порт из двадцати методов — это не граница, а переименование
 * (арх-ревью 28.08.2026).
 *
 * Здесь ровно то, чего диалогу не хватает сверх модели: показать сообщение,
 * закрыть предыдущее окно, перерисовать плитки и спросить у фичи то, что
 * знает только она (статистика игрока, резолв ручного ввода).
 */
import type { PlayerStatsEntry } from "./player-stats";
import type { NotesModel } from "./notes-model";

/** Разобранный ручной ввод «ник или id» из менеджера цветов. */
export interface ResolvedPlayerInput {
  key: string;
  nick: string;
  id?: string;
}

export interface ModalPort {
  /** Владелец данных: карта заметок, палитра и все правила записи. */
  readonly model: NotesModel;
  /** Сообщение пользователю. */
  toast(message: string, warn?: boolean): void;
  /**
   * Зарегистрировать «как закрыть меня». Модалка в проекте одна за раз:
   * открытие второй закрывает первую, а Esc и клик мимо окна закрывают
   * текущую.
   */
  registerModal(close: () => void): void;
  /** Закрыть открытое окно (перед открытием своего). */
  closeOpenModal(): void;
  /** Статистика игрока — её показывает раскрытый редактор заметки. */
  statsOf(username: string): PlayerStatsEntry | undefined;
  /** Разобрать ручной ввод «ник или id» в ключ записи. */
  resolvePlayerInput(input: string): Promise<ResolvedPlayerInput | null>;
  /** Спросить подтверждение на удаление своего цвета из палитры. */
  confirmRemoveCustomTag(css: string): boolean;
  /** Плитки устарели: перерисовать цвета, метки, точки и тултипы. */
  refreshTiles(): void;
  /** Тултипы конкретного игрока. */
  refreshPlayer(username: string): void;
}
